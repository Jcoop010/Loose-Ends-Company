import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const code=readFileSync(new URL('../v3.1/revenue-engine.js',import.meta.url),'utf8')
assert.match(code,/DRAFT · HUMAN REVIEW REQUIRED/)
assert.match(code,/le-autopilot-consent/)
assert.match(code,/le-autopilot-approval/)
assert.match(code,/!consent.checked\|\|!approval.checked/)
assert.match(code,/No message was sent/)
assert.match(code,/consent_reference:reference/)
assert.match(code,/consent_basis:'recorded_consent'/)
assert.match(code,/customer_contact_consent_events/)
assert.match(code,/decision!=='granted'/)
assert.match(code,/consent_event_id:consentEventId/)
assert.match(code,/S\.from\('audit_events'\)\.insert\(record\)/)
assert.match(code,/if\(saved\.error\|\|!saved\.data\|\|!saved\.data\.id\)/)
assert.match(code,/delivery_status:'not_sent'/)
assert.match(code,/action:'enqueue_draft'/)
assert.match(code,/recovery-delivery-preflight/)
assert.match(code,/job\.data&&job\.data\.queued/)
assert.match(code,/await window.LE.recover\(id\)/)
assert.doesNotMatch(code,/fetch\(['"]https?:\/\/[^'"]+\/messages/, 'Draft approval must not trigger outbound delivery')
console.log('Autopilot consent and approval safeguards verified')
